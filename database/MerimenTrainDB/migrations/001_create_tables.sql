USE MerimenTrainDB;
GO

-- 1. Profession Lookup Table (1:M with USR_DATA)
CREATE TABLE dbo.USR_PROF (
    iPROFID     INT IDENTITY(1,1) NOT NULL,
    vaPROFNAME  NVARCHAR(150)     NOT NULL,
    btACTIVE    BIT               NOT NULL CONSTRAINT DF_USR_PROF_btACTIVE DEFAULT (1),
    CONSTRAINT PK_USR_PROF PRIMARY KEY CLUSTERED (iPROFID)
);
GO

-- 2. Hobby Lookup Table (M:N with USR_DATA via USR_HOBBYMAP)
CREATE TABLE dbo.USR_HOBBY (
    iHOBBYID    INT IDENTITY(1,1) NOT NULL,
    vaHOBBYNAME NVARCHAR(150)     NOT NULL,
    vaLOCATION  NVARCHAR(200)     NOT NULL,
    CONSTRAINT PK_USR_HOBBY PRIMARY KEY CLUSTERED (iHOBBYID)
);
GO

-- 3. Main User Biodata Table (Refactored from legacy 'biodata')
CREATE TABLE dbo.USR_DATA (
    iUSERID       INT IDENTITY(1,1) NOT NULL,
    vaNAME        NVARCHAR(255)     NOT NULL,
    vaEMAIL       NVARCHAR(255)     NOT NULL,
    vaPASSWDHASH  NVARCHAR(255)     NOT NULL,
    dtDOB         DATETIME          NULL,
    vaABOUTME     NVARCHAR(1000)    NULL,
    iPROFID       INT               NULL,
    vaIC          NVARCHAR(12)      NOT NULL,      -- Malaysian IC: YYMMDDXXXXXX
    siAGE         SMALLINT          NULL,
    aGENDER       CHAR(1)           NULL,          -- 'M' or 'F'
    bCONTACTMASK  INT               NOT NULL CONSTRAINT DF_USR_DATA_bCONTACTMASK DEFAULT (0),
    mnEXPECTEDSAL MONEY             NOT NULL CONSTRAINT DF_USR_DATA_mnEXPECTEDSAL DEFAULT (0),
    nEXPYEARS     NUMERIC(4,1)      NOT NULL CONSTRAINT DF_USR_DATA_nEXPYEARS DEFAULT (0.0),
    btACTIVE      BIT               NOT NULL CONSTRAINT DF_USR_DATA_btACTIVE DEFAULT (1),
    dtCREATED     DATETIME          NOT NULL CONSTRAINT DF_USR_DATA_dtCREATED DEFAULT (GETDATE()),
    dtUPDATED     DATETIME          NULL,
    CONSTRAINT PK_USR_DATA          PRIMARY KEY CLUSTERED (iUSERID),
    CONSTRAINT UQ_USR_DATA_vaEMAIL  UNIQUE (vaEMAIL),
    CONSTRAINT FK_USR_DATA_iPROFID  FOREIGN KEY (iPROFID) REFERENCES dbo.USR_PROF(iPROFID),
    CONSTRAINT CK_USR_DATA_aGENDER  CHECK (aGENDER IN ('M', 'F'))
);
GO

-- 4. User-Hobby Junction Table (Composite Primary Key prevents duplicates)
CREATE TABLE dbo.USR_HOBBYMAP (
    iUSERID     INT      NOT NULL,
    iHOBBYID    INT      NOT NULL,
    dtASSIGNED  DATETIME NOT NULL CONSTRAINT DF_USR_HOBBYMAP_dtASSIGNED DEFAULT (GETDATE()),
    CONSTRAINT PK_USR_HOBBYMAP          PRIMARY KEY CLUSTERED (iUSERID, iHOBBYID),
    CONSTRAINT FK_USR_HOBBYMAP_iUSERID  FOREIGN KEY (iUSERID)  REFERENCES dbo.USR_DATA(iUSERID),
    CONSTRAINT FK_USR_HOBBYMAP_iHOBBYID FOREIGN KEY (iHOBBYID) REFERENCES dbo.USR_HOBBY(iHOBBYID)
);
GO

-- 5. Audit Log Table (Tracks Insert/Update/Delete activity)
CREATE TABLE dbo.USR_AUDITLOG (
    iLOGID      INT IDENTITY(1,1) NOT NULL,
    iUSERID     INT               NOT NULL,
    aACTION     CHAR(1)           NOT NULL,        -- 'I'=Insert, 'U'=Update, 'D'=Delete
    vaREMARKS   NVARCHAR(300)     NULL,
    dtLOGGED    DATETIME          NOT NULL CONSTRAINT DF_USR_AUDITLOG_dtLOGGED DEFAULT (GETDATE()),
    CONSTRAINT PK_USR_AUDITLOG PRIMARY KEY CLUSTERED (iLOGID)
);
GO